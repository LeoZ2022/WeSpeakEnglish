    //获取一周设置了上课的时间
    public function get_times($teacher_id = 0, $date = '')
    {
        if (!$teacher_id || !$date) {
            $ret = ['code' => 201];
        } else {
            $times = Daytime::get_week_times($teacher_id, $date, get_user_timezone());
            $ret = ['code' => 200, 'data'=>$times];
        }
        echo json_encode($ret);
    }

    //确认下单
    public function confirm()
    {
        $teacher_id = input('teacher_id');
        if (!$this->user_id) {
            $url = url_base64_encode(url('detail', ['teacher_id' => $teacher_id]));
            $this->redirect('sign/learner', ['continue'=>$url]);
        }
        $times = input('times');
        $user = Users::find($this->user_id);
        $teacher = Users::where(['id' => $teacher_id, 'status' => 1, 'close_state' => 0])->find();
        if (!$teacher_id) {
            $this->redirect('/');
        }
        if (!$times) {
            $this->redirect('/');
        }
        $location_login = get_user_timezone();
        $weekauto = input('weekauto', 0);
        $result = Daytime::get_cart($times, $teacher, $user, $location_login, $weekauto);
        if ($result['code']!=200) {
            $this->error($result['msg']);
        }
//        print_r($result);print_r(input('post.'));
        $dayids = $result['dayids'];
        $dates = $result['dates'];
        $times = $result['times'];
        if ($result['code'] == 201) {
            $this->error($result['msg']);
        }
        $cnt = count($dayids);
        $this->assign('cnt', $cnt);
        $this->assign('money', $result['money']);
        $this->assign('invitation_money', $result['invitation_money']);
        $this->assign('invitation_money_use', $result['invitation_money_use']);
        $this->assign('use_money', $result['use_money']);
        $this->assign('pay_money', $result['pay_money']);
        $this->assign('dayids', $dayids);
        $this->assign('dates', $dates);
        $this->assign('times', $times);
        $this->assign('user_info', $user);
        $this->assign('teacher', $teacher);
        $this->assign('teacher_id', $teacher_id);
        $this->assign('daytimes', $result['datas']);

        $device_type = get_device_type();
        $is_wechat_browser = 1;
        if ($device_type > 1) {
            if (!is_wechat_browser()) {
                $is_wechat_browser = 0;
            }
        }
        $this->assign('is_wechat_browser', $is_wechat_browser);

        return $this->fetch();
    }

    public function booked()
    {
        //预约下单
        if ($this->request->isAjax()) {
            $data = input('post.');
            $ret = Order::create_order($data, $this->user_id);
        } else {
            $ret = ['code' => '201', 'msg' => 'Illegal request'];
        }
        echo json_encode($ret);
    }

    //支付成功
    public function succeed($order_id = 0)
    {
        $order = Order::where('id|order_sn', $order_id)->find();
        if (!$order) {
            $this->redirect('/');
        }
        if (!$order['pay_time']) {
            $this->redirect('payment/payagain', ['order_id'=>$order_id]);
        }
        $this->assign('order', $order);
        $teacher = Users::find($order['teacher_id']);
        $this->assign('teacher', $teacher);

        $list = Orderitems::where('order_id', $order['id'])->select();
        $this->assign('lists', $list);

        return $this->fetch();
    }

