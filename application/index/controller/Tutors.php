    public function index()
    {
        if ($this->user_id && $this->user_type == 1) {
            Users::where('id', $this->user_id)->setInc('search_cnt', 1);
            Users::where('id', $this->user_id)->setField('search_time', time());
        }
        $obj = new Tutor();
        if (isset($_GET['page'])) {
            $_POST['page'] = $_GET['page'];
        }

        $location_id = session('?location') ? session('location') : 0;
        if ($location_id) {
            $location_current = Location::find($location_id);
        } else {
            $location_current = Location::where('id', config('cfg_default_location'))->find();
        }
        $this->assign('location_current', $location_current);

        $order = input('order');
        $location = input('location/a', []);
        $this->assign('order', $order);
        $this->assign('location', $location);

        $locations = Location::cache(true)->where(['status' => 1])->select();
        $this->assign('locations', $locations);

        $locations = Country::cache(true)->where(['status' => 1, 'is_teacher'=>1, 'is_delete'=>0])->select();
        $this->assign('countrys', $locations);

//        $times = input('times/a');
        $times_count = 0;
        $this->assign('times_count', $times_count);
        $list = $obj->get_list($location_current);
        $this->assign('list', $list);
        $list = $list->toArray();
        $this->assign('last_page', $list['last_page']);
        $ajax = input('ajax');
        if ($ajax) {
            return $this->fetch('list');
        }

        return $this->fetch();
    }

    public function detail($teacher_id = 0)
    {
        session('teacher_id_jump', $teacher_id);
        if (!$this->user_id) {
            $url = url_base64_encode(url('detail', ['teacher_id' => $teacher_id]));
            $this->redirect('sign/learner', ['continue'=>$url]);
        }
        $login_user = Users::find($this->user_id);
        $this->assign('login_user', $login_user);

        $teacher = Users::find($teacher_id);
        if (!$teacher || !$teacher['email_verify'] || !$teacher['status'] || $teacher['is_locked']) {
            $this->redirect('index');
        }
        $location_login = get_user_timezone();
        $this->assign('location_login', $location_login);
        if (input('ajax') == 1) {
            $comment_list = Orderitems::get_comment_list(['teacher_id' => $teacher_id]);
            $this->assign('comment_list', $comment_list);
            return $this->fetch('get_comment_list');
        }

        $this->assign('teacher_info', $teacher);
        $location = Location::find($teacher['location']);
        $this->assign('location_teacher', $location);
        $location = Country::find($teacher['country_id']);
        $this->assign('country_teacher', $location);

//        $date = time_to_date(time(), $location_login, 'Y-m-d H:i:s');
//        echo $date;
        $date = time_to_date(time(), $location_login, 'Y-m-d');
        $dates = explode('-', $date);
        $this->assign('dates', $dates);

//        $daytimes = Daytime::get_day_30($teacher_id, $location, $location_login, $this->user_id);
//        $this->assign('daytimes', json_encode($daytimes));

        $cnt = Orderitems::alias('c')->where(['teacher_id' => $teacher_id])->where('comment_student_time', 'gt', 0)->count();
        $this->assign('cnt', $cnt);

        $comment_list = Orderitems::get_comment_list(['teacher_id' => $teacher_id]);
        $this->assign('comment_list', $comment_list);

        $date2 = time_to_date(time(), get_user_timezone(), 'Y-m-d H:i:s');
        $time2 = strtotime($date2);
        $this->assign('time_now', $time2);
        $this->assign('date_now', $date2);

        return $this->fetch();
    }

