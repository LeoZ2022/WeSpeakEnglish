    public function check_time($date, $time, $dayid, $teacher_id)
    {
        $time_begin = $time;
        $user_id = $this->user_id;
        $time = strtotime($date);
        $w = date('w', $time);
        $no = 1;
        $dayinfo = Daytime::find($dayid);
        $error_teacher = 0;
        $error_learner = 0;

        $end_date = date('Y-m-d', strtotime('+7 day', strtotime($dayinfo['date']) ));
        $end_date_user = date('Y-m-d', strtotime('+7 day'));
        $teacher = Daytime::where(['user_id' => $teacher_id, 'booked' => 0, 'time'=>$dayinfo['time']])->where('date','between',[$dayinfo['date'], $end_date])->count();
//        echo Daytime::getlastsql();
        if ($teacher < 7) {
            $error_teacher = 1;
            echo json_encode(['error_teacher' => $error_teacher, 'error_learner' => $error_learner]);
            exit;
        }
        $has_leaner = Orderitems::where(['user_id'=>$user_id, 'time_begin' => $time_begin, 'order_status' => 1])->where('book_date', 'between',[$date, $end_date_user])->find();
        if ($has_leaner) {
            $error_learner = 1;
        }
//        echo Orderitems::getlastsql();
        echo json_encode(['error_teacher' => $error_teacher, 'error_learner' => $error_learner]);
        exit;
        while($no < 7) {
            $date_new = date('Y-m-d', strtotime('+'.$no.' day', $time));
            $time_new = strtotime('+'.$no.' day', $dayinfo['datetime']);
            $has_teacher = Daytime::where(['user_id' => $teacher_id, 'booked' => 0, 'datetime'=>$time_new])->find();
            if (!$has_teacher) {
                $error_teacher = 1;
                break;
            }
            $has_leaner = Orderitems::where(['user_id'=>$user_id, 'book_date' => $date_new, 'time_begin' => $time_begin, 'order_status' => 1])->find();
            if ($has_leaner) {
                $error_learner = 1;
                break;
            }
            $no++;$w++;
        }
        if ($no < 7) {
            $error_teacher = 1;
        }
        echo json_encode(['error_teacher' => $error_teacher, 'error_learner' => $error_learner]);
    }

    public function orders()
    {
        $user_id = $this->user_id;
        $orders = Order::alias('o')->field('o.*,username,p.id as pay_id')
            ->join('cms_users m', 'teacher_id = m.id')
            ->join('cms_payment p', 'obj_id = o.id and type=1', 'left')
            ->where('o.user_id', $user_id)->order('o.id desc')->paginate(10);
        foreach ($orders as $k=>$row) {
            $items = Orderitems::where('order_id', $row['id'])->order('id')->select();
            $orders[$k]['items'] = $items;
        }
        $this->assign('lists', $orders);
        $list = $orders->toArray();
        $this->assign('last_page', $list['last_page']);
        if (input('ajax') == 1) {
            return $this->fetch('orders_ajax');
        } else {
            return $this->fetch();
        }
    }

