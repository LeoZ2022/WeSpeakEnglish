    //获取某一天的课程列表
    public function get_list($date)
    {
        $index = input('index', 0);
        $size = 20;
        if ($index) {
            $size = 10;
        }
        $this->assign('index', $index);
        $countrys = Country::get_list_col();
        $locations = Location::get_list_col();
        $english_level = config('english_level');
        $native_language = config('native_language');
        $date = date('Y-m-d', strtotime($date));
        $user_id = $this->user_id;
        $user_type = $this->user_type;
        $time = strtotime('-30 minute');
        $date_now = time_to_date($time, get_user_timezone(), 'Y-m-d H:i');
        $dates = explode(' ', $date_now);
//        print_r($dates);print_r(get_user_timezone());
        if ($user_type == 1) {
            $map = [ ['user_id', 'eq', $user_id], ['book_date', 'eq', $date]];
            $join_col = 'teacher_id';
            $field = 'i.*, goals,username,native_language,english_level,location as location_id_s,descr as descr, country_id, goals';
            if ($dates[0] == $date) {
                //如果是当天的，只显示当前时间后的
                $map[] = ['time_begin', 'gt', $dates[1]];
            }
        } else {
            $field = 'i.*, goals,username,native_language,english_level,location as location_id_s,descr as descr, country_id, goals';
            $map = [ ['teacher_id', 'eq', $user_id], ['book_date_teacher', 'eq', $date]];
            $join_col = 'user_id';
            if ($dates[0] == $date) {
                //如果是当天的，只显示当前时间后的
                $map[] = ['time_begin_teacher', 'gt', $dates[1]];
            }
        }
        $map[] = ['order_status', 'eq', 1];
        $list = Orderitems::alias('i')->field($field)
            ->join('cms_users u', "{$join_col} = u.id")
            ->where($map)->order('i.datetime')->paginate($size, false, [
                'query' => ['date'=>$date]
            ]);
        $lists = $list->toArray();
        if ($user_type == 1) {
            $out = $lists['data'];
        } else {
            $out = [];
            foreach ($lists['data'] as $k => $row) {
                $out[$k] = $row;
                $out[$k]['first'] = $native_language[$row['native_language']];
                $out[$k]['levels'] = $english_level[$row['english_level']];
                $out[$k]['location_name'] = $countrys[$row['country_id']]['country_name'] ?? '';
                $out[$k]['location_ico'] = $countrys[$row['country_id']]['ico_file'] ?? '';
            }
        }
        $this->assign('lists', $out);
        $this->assign('list', $list);

        $time3 = strtotime('+'. config('cfg_cancel_time').' hour');
        $this->assign('time3', $time3);
        return $this->fetch();
    }

